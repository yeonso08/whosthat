/**
 * 브랜드 이름의 조각.
 *
 * 워드마크는 `@누꼬`(ko)·`@nukko`(en), 마크는 그 앞의 `@` 하나다. 헤더 워드마크와
 * 파비콘·앱 아이콘이 같은 글자를 그리므로 한 곳에 둔다.
 */

import type { Locale } from "./locales";

/**
 * 파비콘과 앱 아이콘이 그리는 마크. 워드마크 앞의 `@` 와 같은 글자다.
 *
 * **언어를 타지 않는다.** `icon.tsx`·`apple-icon.tsx` 는 `[lang]` 바깥이라 애초에
 * 언어를 못 받고, 그래서 두 언어가 이 한 글자를 공유한다. 이름이 `whosthat` 에서
 * `nukko` 로 바뀌었는데도 이 값이 그대로인 건 `@` 가 가리키는 것이 브랜드가 아니라
 * 인스타그램이기 때문이다 — 이름이 또 바뀌어도 여기는 안 바뀐다.
 */
export const BRAND_MARK = "@";

/**
 * 워드마크의 이름 부분.
 *
 * `누꼬` 는 `nukko` 의 번역이 아니라 **원문**이라 언어를 따라간다 — 한국어 화면이
 * 원문 대신 로마자 표기를 쓸 이유가 없다. (`whosthat` 시절 한글 워드마크를 반려한
 * 건 그때는 그게 번역이었기 때문이다. 이름이 사투리로 바뀌면서 조건이 뒤집혔다.)
 */
export const BRAND_WORDMARK: Record<Locale, string> = {
  ko: "누꼬",
  en: "nukko",
};

/**
 * 이름 부분에 붙일 서체. 라틴 이름만 `font-lat`(Manrope)이고 한글은 본문
 * 서체(Gothic A1)를 쓴다 — 프로젝트 규칙(라틴·숫자는 `font-lat`) 그대로다.
 *
 * **마크(`@`)는 어느 언어에서도 `font-lat` 이다.** Gothic A1 의 `@` 는 안쪽 `a`
 * 배가 작고 둥글어서, 이름과 같은 서체로 두면 언어를 전환할 때 마크가 다른 글자로
 * 읽힌다. 파비콘의 `@` 와 같은 글리프를 유지하려면 이름만 갈아 끼워야 한다.
 *
 * 한글 쪽을 빈 문자열이 아니라 `font-sans` 로 못박은 건 이 값이 `font-lat` 을 이미
 * 걸어 둔 상자 안(푸터 카피라이트 줄)에도 들어가기 때문이다.
 */
export const BRAND_WORDMARK_FONT: Record<Locale, string> = {
  ko: "font-sans",
  en: "font-lat",
};
